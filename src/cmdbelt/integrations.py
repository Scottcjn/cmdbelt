"""Install snippets for agent integrations. Nothing here edits user files."""

from __future__ import annotations

import json
import shutil
import sys
from pathlib import Path

from .rules import Rule, load_builtin_rules

CLAUDE_SETTINGS_FILES = (
    "~/.claude/settings.json (user)",
    ".claude/settings.json (project, committed)",
    ".claude/settings.local.json (project, local)",
)


def cmdbelt_path() -> str:
    found = shutil.which("cmdbelt")
    if found:
        return found
    # fall back to the interpreter running us (works inside a venv / pipx)
    return f"{sys.executable} -m cmdbelt"


def claude_code_snippet(home: str | None = None) -> str:
    exe = cmdbelt_path()
    cmd = f"{exe} hook claude-code" + (f" --home {home}" if home else "")
    settings = {
        "hooks": {
            "PreToolUse": [
                {
                    "matcher": "Bash",
                    "hooks": [{"type": "command", "command": cmd, "timeout": 120}],
                }
            ]
        }
    }
    files = "\n".join(f"#   - {f}" for f in CLAUDE_SETTINGS_FILES)
    return (
        "# Claude Code: add this to ONE of\n"
        f"{files}\n"
        '# (merge into an existing "hooks" object if you already have one).\n'
        "# cmdbelt never edits these files for you.\n"
        f"{json.dumps(settings, indent=2)}\n"
        "# Contract: deny -> exit 2 + reason on stderr (Claude sees it);\n"
        '#           ask  -> JSON permissionDecision "ask" (you see the reason in the prompt);\n'
        "#           allow -> silent, your normal Claude Code permission rules still apply.\n"
        '# Verify:  echo \'{"tool_name":"Bash","tool_input":{"command":"rm -rf /"}}\' | '
        f"{cmd}; echo exit=$?\n"
    )


def codex_hooks_snippet(home: str | None = None, codex_ask: str = "deny") -> str:
    exe = cmdbelt_path()
    extra = (f" --home {home}" if home else "") + (
        f" --codex-ask {codex_ask}" if codex_ask != "deny" else ""
    )
    hooks = {
        "PreToolUse": [
            {
                "matcher": "Bash",
                "hooks": [
                    {
                        "type": "command",
                        "command": f"{exe} hook codex{extra}",
                        "statusMessage": "cmdbelt policy check",
                        "timeout": 120,
                    }
                ],
            }
        ],
        "PermissionRequest": [
            {
                "matcher": "Bash",
                "hooks": [
                    {
                        "type": "command",
                        "command": f"{exe} hook codex --event PermissionRequest{extra}",
                        "timeout": 60,
                    }
                ],
            }
        ],
    }
    return (
        "# Codex CLI: save as ~/.codex/hooks.json (user) or <repo>/.codex/hooks.json (project),\n"
        "# then run /hooks inside Codex to review + trust it. Hooks are on by default\n"
        "# ([features] hooks = false disables them). cmdbelt never edits these files.\n"
        f"{json.dumps(hooks, indent=2)}\n"
        '# IMPORTANT: Codex PreToolUse hooks cannot return "ask" (Codex treats it as a failed\n'
        "# hook and continues). cmdbelt therefore turns 'ask' into a deny for Codex by default\n"
        "# (--codex-ask deny). To get real prompts, also install the generated rules file:\n"
        "#   cmdbelt install codex --rules > ~/.codex/rules/cmdbelt.rules\n"
        "#   codex execpolicy check --rules ~/.codex/rules/cmdbelt.rules -- docker system prune\n"
    )


def _starlark_list(items: list[str]) -> str:
    return "[" + ", ".join(json.dumps(x) for x in items) + "]"


def codex_rules(rules: list[Rule] | None = None) -> str:
    """Translate the subset of rules that are plain argv prefixes into Codex prefix_rule()s.

    Codex execpolicy matches *leading arguments only* (no flags/paths/pipes), so only
    rules whose matcher is cmd (+ subcmd (+ subcmd2)) with nothing else can be
    expressed. Everything else stays in the hook.
    """
    rules = rules if rules is not None else load_builtin_rules()
    out = [
        "# Generated by `cmdbelt install codex --rules`. Starlark syntax for Codex execpolicy.",
        "# Only prefix-expressible cmdbelt rules appear here; flag/path/pipe-based rules",
        "# (rm -rf /, curl | sh, git push --force main, ...) are enforced by the hook.",
        "",
    ]
    decision_map = {"deny": "forbidden", "ask": "prompt"}
    n = 0
    for r in rules:
        if r.action not in decision_map or not r.cmd:
            continue
        if any(
            [
                r.flags_any,
                r.flags_all,
                r.flags_none,
                r.args_any,
                r.args_regex,
                r.args_path_any,
                r.args_path_none,
                r.regex,
                r.text_regex,
                r.redirect_path_any,
                r.pipe_from,
                r.pipe_from_any,
                r.wrappers_any,
                r.remote is not None,
                r.dynamic_args is not None,
                r.min_positional is not None,
                r.max_positional is not None,
            ]
        ):
            continue
        pattern: list[str] = []
        pattern.append(_starlark_list(r.cmd) if len(r.cmd) > 1 else json.dumps(r.cmd[0]))
        for level in (r.subcmd, r.subcmd2):
            if level:
                pattern.append(_starlark_list(level) if len(level) > 1 else json.dumps(level[0]))
        out.append(
            "prefix_rule(\n"
            f"    pattern = [{', '.join(pattern)}],\n"
            f"    decision = {json.dumps(decision_map[r.action])},\n"
            f"    justification = {json.dumps(f'cmdbelt {r.id}: {r.reason}')},\n"
            ")"
        )
        n += 1
    out.append(f"\n# {n} rules translated.")
    return "\n".join(out) + "\n"


def shim_snippet() -> str:
    return (
        "# PATH shim (weakest option; for agents with no hook mechanism).\n"
        "# Put a directory first on PATH containing wrappers that route through cmdbelt:\n"
        "mkdir -p ~/.agent-guard/shims\n"
        "for c in rm git docker kubectl systemctl; do\n"
        '  printf \'#!/bin/sh\\nexec cmdbelt exec --shim -- %s "$@"\\n\' "$c" '
        "> ~/.agent-guard/shims/$c\n"
        "  chmod +x ~/.agent-guard/shims/$c\n"
        "done\n"
        "export PATH=~/.agent-guard/shims:$PATH   # in the agent's environment only\n"
        "# Limits: only wrapped commands are seen; absolute paths (/bin/rm), shell builtins,\n"
        "# redirections and pipelines bypass it. Prefer a real hook whenever one exists.\n"
    )


def install_text(target: str, *, home: str | None, rules_only: bool, codex_ask: str) -> str:
    if target == "claude-code":
        return claude_code_snippet(home)
    if target == "codex":
        if rules_only:
            return codex_rules()
        return codex_hooks_snippet(home, codex_ask)
    if target == "shim":
        return shim_snippet()
    raise ValueError(f"unknown integration: {target}")


def guard_home_hint(home: Path) -> str:
    return f"# cmdbelt home: {home} (config.toml, audit.jsonl, budgets.sqlite, snapshots/)\n"
