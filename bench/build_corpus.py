"""Build bench/corpus.jsonl (>=500 labelled commands). Deterministic.

Labels:
  expected="allow"  -> benign: any ask/deny counts as a FALSE POSITIVE
  expected="caught" -> dangerous: an allow counts as a FALSE NEGATIVE (ask or deny = caught)

Sources:
  rules-table : the labelled cases in tests/test_rules.py (SPEC deny/ask list + evasions)
  templates   : the same dangerous base commands wrapped in sudo/env/bash -c/ssh/etc.
  incident    : commands of the class in openai/codex #59060 ("destroyed systemd, mounts,
                containers") and our lab incidents (volume prune, pkill sweep, checkout --)
  benign      : written here from templates of everyday agent work. No transcripts were read.
"""

from __future__ import annotations

import ast
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
OUT = HERE / "corpus.jsonl"

rows: list[dict[str, str]] = []
seen: set[str] = set()


def add(expected: str, category: str, source: str, cmds: list[str]) -> None:
    for c in cmds:
        if c and c not in seen:
            seen.add(c)
            rows.append(
                {"command": c, "expected": expected, "category": category, "source": source}
            )


def rule_table_cases() -> list[tuple[str, str]]:
    """(command, action) pairs from tests/test_rules.py CASES without importing pytest."""
    src = (ROOT / "tests" / "test_rules.py").read_text()
    tree = ast.parse(src)
    for node in tree.body:
        if isinstance(node, ast.AnnAssign) and getattr(node.target, "id", "") == "CASES":
            out: list[tuple[str, str]] = []
            for elt in getattr(node.value, "elts", []):
                try:
                    c, a, _ = ast.literal_eval(elt)
                except ValueError:
                    continue  # f-string entries (home-relative) are skipped
                if c.strip():
                    out.append((c, a))
            return out
    raise SystemExit("CASES not found")


# ---- dangerous: from the rule test table -------------------------------------------
for command, action in rule_table_cases():
    if action in ("deny", "ask"):
        add("caught", "rules-table", "spec", [command])
    else:
        add("allow", "rules-table-benign", "spec", [command])

